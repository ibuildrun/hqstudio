        public static IReadOnlyList<GuideSection> Sections { get; } = Build();

        public static GuideSection? Find(string? id) =>
            Sections.FirstOrDefault(s => string.Equals(s.Id, id, StringComparison.Ordinal));

        /// <summary>Весь текст инструкции вместе с адресами ссылок: для проверок содержимого.</summary>
        public static IEnumerable<string> AllText() => Sections.SelectMany(s => s.AllText());

        public static IEnumerable<string> AllUrls() => Sections
            .SelectMany(s => s.Steps)
            .SelectMany(step => step.LinkList)
            .Select(link => link.Url);

        private static IReadOnlyList<GuideStep> Numbered(params GuideStep[] steps) =>
            steps.Select((step, index) => step with { Number = index + 1 }).ToList();

